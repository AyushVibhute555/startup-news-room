import sanitizeHtml from 'sanitize-html';
import * as cheerio from 'cheerio';

/** Strips ALL HTML tags and returns plain text (Used for Titles, Summaries, Tags). */
export function stripHtml(input: string): string {
    return cheerio.load(
        sanitizeHtml(input, { allowedTags: [], allowedAttributes: {} }),
        null,
        false,
    )
        .text()
        .replace(/\s+/g, ' ')
        .trim();
}

function escapeHtml(input: string): string {
    return input
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

function markdownInline(input: string): string {
    return escapeHtml(input)
        .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
}

function markdownToHtml(input: string): string {
    const blocks: string[] = [];
    let paragraph: string[] = [];
    let listItems: string[] = [];
    let listTag: 'ul' | 'ol' | null = null;

    const flushParagraph = () => {
        if (paragraph.length) {
            blocks.push(`<p>${paragraph.map(markdownInline).join('<br>')}</p>`);
            paragraph = [];
        }
    };
    const flushList = () => {
        if (listTag && listItems.length) {
            blocks.push(`<${listTag}>${listItems.map((item) => `<li>${markdownInline(item)}</li>`).join('')}</${listTag}>`);
        }
        listItems = [];
        listTag = null;
    };

    for (const line of input.replace(/\r\n?/g, '\n').split('\n')) {
        const heading = line.match(/^(#{1,3})\s+(.+)$/);
        const unorderedItem = line.match(/^\s*[-*+]\s+(.+)$/);
        const orderedItem = line.match(/^\s*\d+[.)]\s+(.+)$/);
        const item = unorderedItem ?? orderedItem;
        const headingMarks = heading?.[1];
        const headingText = heading?.[2];
        const itemText = item?.[1];

        if (headingMarks && headingText) {
            flushParagraph();
            flushList();
            const level = Math.min(headingMarks.length + 1, 4);
            blocks.push(`<h${level}>${markdownInline(headingText)}</h${level}>`);
        } else if (itemText !== undefined) {
            flushParagraph();
            const nextListTag = unorderedItem ? 'ul' : 'ol';
            if (listTag && listTag !== nextListTag) flushList();
            listTag = nextListTag;
            listItems.push(itemText);
        } else if (!line.trim()) {
            flushParagraph();
            flushList();
        } else {
            flushList();
            paragraph.push(line);
        }
    }

    flushParagraph();
    flushList();
    return blocks.join('');
}

/** Converts plain-text Markdown to safe semantic HTML and preserves legacy HTML. */
export function sanitizeContent(input: string): string {
    const content = /<\/?[a-z][\w:-]*(?:\s[^<>]*?)?\s*\/?>/i.test(input)
        ? input
        : markdownToHtml(input);

    return sanitizeHtml(content, {
        allowedTags: [
            'table', 'thead', 'tbody', 'tfoot', 'tr', 'th', 'td',
            'b', 'strong', 'i', 'em', 'u',
            'p', 'br', 'ul', 'ol', 'li',
            'h2', 'h3', 'h4', 'blockquote',
            'a', 'img', 'span'
        ],
        allowedAttributes: {
            'a': ['href', 'target', 'rel'],
            'img': ['src', 'alt', 'width', 'height'],
            'table': ['style', 'border', 'cellpadding', 'cellspacing'],
            'td': ['style', 'colspan', 'rowspan', 'width'],
            'th': ['style', 'colspan', 'rowspan', 'width'],
            '*': ['style']
        },
        // Allow safe inline styles usually generated by Word/Google Docs tables
        allowedStyles: {
            '*': {
                'text-align': [/^left$/, /^right$/, /^center$/],
                'font-weight': [/^bold$/, /^[0-9]+$/],
                'font-style': [/^italic$/],
                'text-decoration': [/^underline$/],
                'border': [/^.*$/],
                'border-collapse': [/^.*$/],
                'width': [/^.*$/],
                'padding': [/^.*$/],
                'margin': [/^.*$/],
                'background-color': [/^.*$/]
            }
        }
    });
}
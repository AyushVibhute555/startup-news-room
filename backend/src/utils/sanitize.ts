import sanitizeHtml from 'sanitize-html';

/** Strips ALL HTML tags and returns plain text (Used for Titles, Summaries, Tags). */
export function stripHtml(input: string): string {
    return sanitizeHtml(input, { allowedTags: [], allowedAttributes: {} })
        .replace(/\s+/g, ' ')
        .trim();
}

/** 
 * Allows safe HTML formatting like tables, bold text, and lists 
 * (Used ONLY for the Story Content body).
 */
export function sanitizeContent(input: string): string {
    return sanitizeHtml(input, {
        allowedTags: [
            'table', 'thead', 'tbody', 'tfoot', 'tr', 'th', 'td',
            'b', 'strong', 'i', 'em', 'u',
            'p', 'br', 'ul', 'ol', 'li',
            'h2', 'h3', 'h4', 'blockquote',
            'a', 'img', 'span'
        ],
        allowedAttributes: {
            'a': ['href', 'target', 'rel'],
            'img': ['src', 'alt', 'width', 'height'],
            'table': ['style', 'border', 'cellpadding', 'cellspacing'],
            'td': ['style', 'colspan', 'rowspan', 'width'],
            'th': ['style', 'colspan', 'rowspan', 'width'],
            '*': ['style']
        },
        // Allow safe inline styles usually generated by Word/Google Docs tables
        allowedStyles: {
            '*': {
                'text-align': [/^left$/, /^right$/, /^center$/],
                'font-weight': [/^bold$/, /^[0-9]+$/],
                'font-style': [/^italic$/],
                'text-decoration': [/^underline$/],
                'border': [/^.*$/],
                'border-collapse': [/^.*$/],
                'width': [/^.*$/],
                'padding': [/^.*$/],
                'margin': [/^.*$/],
                'background-color': [/^.*$/]
            }
        }
    });
}
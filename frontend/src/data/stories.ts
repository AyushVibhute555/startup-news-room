const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "")
    .slice(0, 80);

const now = Date.now();

export const stories: Story[] = seeds.map(
  ([title, summary, category, source, image, hoursAgo, tags, flags], i) => {
    const slug = slugify(title);
    return {
      _id: `story_${String(i + 1).padStart(3, "0")}`,
      title,
      slug,
      summary,
      content:
        "Our editors summarised this report from the original source. Details, figures and quotes are attributed to the publisher linked below, where you can read the full story.",
      imageUrl: img(image),
      imageCredit: "Photo: Unsplash",
      sourceName: source,
      sourceUrl: `https://example.com/${slug}`,
      category,
      tags,
      publishedAt: new Date(now - hoursAgo * 3600_000 - 7 * 60_000).toISOString(),
      readTime: 2 + (i % 4),
      isFeatured: !!flags?.featured,
      isBreaking: !!flags?.breaking,
    };
  },
);
